import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { stringify } from "yaml";
import { loadWrapperConfig } from "./root.js";

export function listAgents(root: string): string[] {
  const dir = join(root, "agents");
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(dir, e.name, "agent.yaml")))
    .map((e) => e.name)
    .sort();
}

export function serviceName(agent: string): string {
  return `agent-${agent}`;
}

/**
 * Generates the root docker-compose.yml: the Langfuse stack is pulled in via
 * `include:` and one hardened service is emitted per agent.
 */
export function generateCompose(root: string): string {
  const agents = listAgents(root);
  const { langfuse } = loadWrapperConfig(root);
  // external: bring-your-own Langfuse — no bundled stack, no dependency on it.
  const langfuseUrl = langfuse.external
    ? langfuse.containerBaseUrl ?? langfuse.baseUrl
    : "http://langfuse-web:3000";

  const services: Record<string, unknown> = {};
  for (const name of agents) {
    // An agent-local Dockerfile (extending wrapper-runtime) wins over the shared image.
    const customDockerfile = existsSync(join(root, "agents", name, "Dockerfile"));
    services[serviceName(name)] = {
      image: customDockerfile ? `wrapper-agent-${name}:latest` : "wrapper-runtime:latest",
      build: customDockerfile
        ? { context: ".", dockerfile: `agents/${name}/Dockerfile` }
        : { context: ".", dockerfile: "docker/runtime.Dockerfile" },
      restart: "unless-stopped",
      // later files override earlier: per-agent > agents/.env > root .env
      env_file: [
        ...(existsSync(join(root, ".env")) ? ["./.env"] : []),
        ...(existsSync(join(root, "agents", ".env")) ? ["./agents/.env"] : []),
        `./agents/${name}/.env`,
      ],
      environment: {
        // Mounted under /app so tool modules resolve pi packages from /app/node_modules.
        AGENT_DIR: "/app/agent",
        DATA_DIR: "/data",
        LANGFUSE_BASEURL: langfuseUrl,
      },
      volumes: [`./agents/${name}:/app/agent:ro`, `${name}-data:/data`],
      networks: ["wrapper_net"],
      // isolation defaults (DESIGN.md §Isolation model)
      user: "node",
      read_only: true,
      tmpfs: ["/tmp"],
      cap_drop: ["ALL"],
      security_opt: ["no-new-privileges:true"],
      mem_limit: "1g",
      cpus: 1,
      pids_limit: 256,
      ...(langfuse.external
        ? {}
        : { depends_on: { "langfuse-web": { condition: "service_healthy" } } }),
    };
  }

  const compose: Record<string, unknown> = {
    name: "wrapper",
    // wrapper_net is normally defined by the included Langfuse stack file.
    ...(langfuse.external
      ? { networks: { wrapper_net: { name: "wrapper_net" } } } // same name the stack file uses
      : { include: [{ path: "infra/langfuse/docker-compose.yml" }] }),
    services,
    volumes: Object.fromEntries(agents.map((a) => [`${a}-data`, {}])),
  };
  if (agents.length === 0) {
    delete compose.services;
    delete compose.volumes;
  }

  const header =
    "# GENERATED by `wrapper` — do not edit by hand. Regenerate with any `wrapper agent` command.\n";
  const yamlText = header + stringify(compose);
  writeFileSync(join(root, "docker-compose.yml"), yamlText);
  return yamlText;
}
