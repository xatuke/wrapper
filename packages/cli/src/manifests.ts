import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { stringify } from "yaml";
import { listAgents } from "./compose.js";
import type { K8sConfig } from "./root.js";

export function agentImage(k8s: K8sConfig, name: string): string {
  return `${k8s.registry}/${k8s.repoPrefix}/agents/${name}:latest`;
}

export function runtimeImage(k8s: K8sConfig): string {
  return `${k8s.registry}/${k8s.repoPrefix}/wrapper-runtime:latest`;
}

export function deploymentName(agent: string): string {
  return `agent-${agent}`;
}

export function secretName(agent: string): string {
  return `agent-${agent}-env`;
}

function namespaceManifests(k8s: K8sConfig): object[] {
  return [
    {
      apiVersion: "v1",
      kind: "Namespace",
      metadata: { name: k8s.namespace, labels: { "app.kubernetes.io/managed-by": "wrapper" } },
    },
    {
      apiVersion: "v1",
      kind: "ServiceAccount",
      metadata: {
        name: k8s.serviceAccount,
        namespace: k8s.namespace,
        // IRSA role annotation is added by `wrapper` provisioning (kept out of
        // the generated file so regeneration never strips it: we patch live).
      },
    },
  ];
}

function agentManifests(k8s: K8sConfig, name: string): object[] {
  const labels = { app: "wrapper-agent", agent: name };
  return [
    {
      apiVersion: "v1",
      kind: "PersistentVolumeClaim",
      metadata: { name: `${deploymentName(name)}-data`, namespace: k8s.namespace, labels },
      spec: {
        accessModes: ["ReadWriteOnce"],
        storageClassName: k8s.storageClass,
        resources: { requests: { storage: "1Gi" } },
      },
    },
    {
      apiVersion: "apps/v1",
      kind: "Deployment",
      metadata: { name: deploymentName(name), namespace: k8s.namespace, labels },
      spec: {
        replicas: 1,
        // Recreate: two live pods would both hold Socket Mode connections and
        // split incoming Slack events between them.
        strategy: { type: "Recreate" },
        selector: { matchLabels: labels },
        template: {
          metadata: { labels },
          spec: {
            serviceAccountName: k8s.serviceAccount,
            nodeSelector: { "kubernetes.io/arch": k8s.arch },
            securityContext: {
              runAsNonRoot: true,
              runAsUser: 1000,
              runAsGroup: 1000,
              fsGroup: 1000, // makes the PVC writable by the node user
              seccompProfile: { type: "RuntimeDefault" },
            },
            containers: [
              {
                name: "agent",
                image: agentImage(k8s, name),
                imagePullPolicy: "Always",
                envFrom: [{ secretRef: { name: secretName(name) } }],
                env: [
                  { name: "AGENT_DIR", value: "/app/agent" },
                  { name: "DATA_DIR", value: "/data" },
                  // Only meaningful on AWS (Bedrock/IRSA); omitted elsewhere.
                  ...(k8s.awsRegion ? [{ name: "AWS_REGION", value: k8s.awsRegion }] : []),
                  { name: "LANGFUSE_BASEURL", value: k8s.langfuseBaseUrl },
                ],
                volumeMounts: [
                  { name: "data", mountPath: "/data" },
                  { name: "tmp", mountPath: "/tmp" },
                ],
                securityContext: {
                  readOnlyRootFilesystem: true,
                  allowPrivilegeEscalation: false,
                  capabilities: { drop: ["ALL"] },
                },
                resources: {
                  requests: { cpu: "100m", memory: "256Mi" },
                  limits: { cpu: "1", memory: "1Gi" },
                },
              },
            ],
            volumes: [
              { name: "data", persistentVolumeClaim: { claimName: `${deploymentName(name)}-data` } },
              { name: "tmp", emptyDir: {} },
            ],
          },
        },
      },
    },
  ];
}

/**
 * Writes k8s/namespace.yaml and k8s/agents/<name>.yaml. Secrets are NOT
 * generated here — they're created imperatively from each agent's .env at
 * apply time so secret material never lands in a manifest file.
 */
export function generateManifests(root: string, k8s: K8sConfig): string[] {
  const outDir = join(root, "k8s");
  mkdirSync(join(outDir, "agents"), { recursive: true });

  const header = "# GENERATED by `wrapper` — do not edit by hand.\n";
  const files: string[] = [];

  const nsFile = join(outDir, "namespace.yaml");
  writeFileSync(nsFile, header + namespaceManifests(k8s).map((m) => stringify(m)).join("---\n"));
  files.push(nsFile);

  for (const name of listAgents(root)) {
    const file = join(outDir, "agents", `${name}.yaml`);
    writeFileSync(file, header + agentManifests(k8s, name).map((m) => stringify(m)).join("---\n"));
    files.push(file);
  }
  return files;
}

/**
 * The k8s image must contain the agent's files (no bind mounts in a cluster).
 * Returns a Dockerfile that layers the agent dir onto its base image — the
 * agent's own Dockerfile image if it has one, else the shared runtime.
 */
export function agentImageDockerfile(root: string, k8s: K8sConfig, name: string): string {
  const base = existsSync(join(root, "agents", name, "Dockerfile"))
    ? `wrapper-agent-${name}:build` // custom image built locally first
    : runtimeImage(k8s);
  return `FROM ${base}\nCOPY --chown=node:node agents/${name} /app/agent\n`;
}
